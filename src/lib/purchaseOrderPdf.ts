import { jsPDF } from "jspdf";
import { format } from "date-fns";

export interface POPdfItem {
  product_name: string;
  category?: string | null;
  unit?: string | null;
  quantity: number;
  unit_cost: number;
  total_cost: number;
}

export interface POPdfData {
  shop: { name: string; address?: string | null; phone?: string | null; email?: string | null; logo_url?: string | null };
  supplier: { name: string; contact_person?: string | null; phone?: string | null; email?: string | null; address?: string | null };
  poNumber: string;
  date: Date | string;
  items: POPdfItem[];
  total: number;
  notes?: string | null;
  currency?: string;
}

const money = (n: number) => new Intl.NumberFormat("en-US", { maximumFractionDigits: 0 }).format(n || 0);

async function loadImageDataUrl(url: string): Promise<string | null> {
  try {
    const res = await fetch(url);
    if (!res.ok) return null;
    const blob = await res.blob();
    return await new Promise((resolve) => {
      const reader = new FileReader();
      reader.onloadend = () => resolve(reader.result as string);
      reader.onerror = () => resolve(null);
      reader.readAsDataURL(blob);
    });
  } catch {
    return null;
  }
}

/** Generates a professional A4 purchase order PDF. */
export async function generatePurchaseOrderPdf(data: POPdfData): Promise<Blob> {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const W = 210;
  const M = 15;
  const cur = data.currency || "UGX";
  let y = 16;

  if (data.shop.logo_url) {
    const img = await loadImageDataUrl(data.shop.logo_url);
    if (img) {
      try { doc.addImage(img, "PNG", M, y - 4, 22, 22); } catch { /* ignore */ }
    }
  }

  doc.setFont("helvetica", "bold");
  doc.setFontSize(16);
  doc.text(data.shop.name, M + 26, y + 3);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  const shopLines = [data.shop.address, data.shop.phone, data.shop.email].filter(Boolean) as string[];
  shopLines.forEach((l, i) => doc.text(l, M + 26, y + 9 + i * 4.5));

  doc.setFont("helvetica", "bold");
  doc.setFontSize(15);
  doc.text("PURCHASE ORDER", W - M, y + 3, { align: "right" });
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.text(`No: ${data.poNumber}`, W - M, y + 9, { align: "right" });
  doc.text(`Date: ${format(new Date(data.date), "dd MMM yyyy")}`, W - M, y + 13.5, { align: "right" });

  y += 26 + Math.max(0, (shopLines.length - 2) * 4.5);
  doc.setDrawColor(210);
  doc.line(M, y, W - M, y);
  y += 8;

  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  doc.text("Supplier", M, y);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  y += 5;
  const supLines = [
    data.supplier.name,
    data.supplier.contact_person || "",
    data.supplier.phone || "",
    data.supplier.email || "",
    data.supplier.address || "",
  ].filter(Boolean);
  supLines.forEach((l) => { doc.text(String(l), M, y); y += 4.5; });

  y += 5;

  // Table header
  const cols = [M, M + 66, M + 100, M + 118, M + 145, W - M];
  doc.setFillColor(242, 242, 242);
  doc.rect(M, y - 5, W - 2 * M, 8, "F");
  doc.setFont("helvetica", "bold");
  doc.setFontSize(8.5);
  doc.text("Product", cols[0] + 2, y);
  doc.text("Category", cols[1], y);
  doc.text("Unit", cols[2], y);
  doc.text("Qty", cols[3] + 14, y, { align: "right" });
  doc.text("Unit Cost", cols[4] + 16, y, { align: "right" });
  doc.text("Total", cols[5] - 2, y, { align: "right" });
  y += 8;

  doc.setFont("helvetica", "normal");
  let totalQty = 0;
  for (const it of data.items) {
    if (y > 265) { doc.addPage(); y = 20; }
    const name = doc.splitTextToSize(it.product_name, 62)[0];
    doc.text(String(name), cols[0] + 2, y);
    doc.text(String(it.category || "—").slice(0, 18), cols[1], y);
    doc.text(String(it.unit || "piece").slice(0, 10), cols[2], y);
    doc.text(String(it.quantity), cols[3] + 14, y, { align: "right" });
    doc.text(money(it.unit_cost), cols[4] + 16, y, { align: "right" });
    doc.text(money(it.total_cost), cols[5] - 2, y, { align: "right" });
    totalQty += Number(it.quantity) || 0;
    y += 6;
  }

  doc.setDrawColor(210);
  doc.line(M, y, W - M, y);
  y += 6;
  doc.setFontSize(9);
  doc.text(`Total items: ${data.items.length}   ·   Total quantity: ${totalQty}`, M, y);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.text(`TOTAL: ${cur} ${money(data.total)}`, W - M, y, { align: "right" });

  if (data.notes) {
    y += 10;
    doc.setFont("helvetica", "bold");
    doc.setFontSize(9);
    doc.text("Notes", M, y);
    doc.setFont("helvetica", "normal");
    y += 5;
    doc.splitTextToSize(data.notes, W - 2 * M).forEach((l: string) => { doc.text(l, M, y); y += 4.5; });
  }

  y += 14;
  doc.setFontSize(8);
  doc.setTextColor(120);
  doc.text("Generated by ShopTracker", M, y);

  return doc.output("blob");
}
